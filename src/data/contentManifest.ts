/*
 * ══════════════════════════════════════════════════════════════════
 *
 *   MANIFIESTO DE CONTENIDO — la única fuente de verdad de los IDs
 *
 *   Cada elemento del jardín que necesita algo tuyo aparece aquí una
 *   sola vez, con su identificador. De este archivo salen:
 *
 *     · CONTENT_GUIDE.md      (npm run content:guide)
 *     · los IDs del modo autor  (abre la página con #author)
 *     · la lista del modo contenido (#content)
 *
 *   NO edites aquí los textos del regalo: viven en src/data/garden.ts
 *   y en src/data/audio.ts. Aquí sólo se describe QUÉ hace falta.
 *
 *   Los identificadores son correlativos y no deben reutilizarse.
 *   Si añades un elemento nuevo, dale el siguiente número libre y
 *   vuelve a generar la guía.
 *
 * ══════════════════════════════════════════════════════════════════
 */

/** Qué clase de cosa hay que proporcionar. */
export type ContentType =
  | 'text'
  | 'paragraphs'
  | 'quote'
  | 'photo'
  | 'video'
  | 'playlistUrl'
  | 'song'
  | 'fact'
  | 'place'
  | 'url'
  | 'audio'
  | 'choice'
  | 'title'
  | 'settings'

export interface ContentItem {
  /** Identificador único y estable. El mismo en la guía y en la página. */
  id: string
  /** Dónde vive el valor dentro de los datos. */
  path: string
  /** Qué archivo hay que abrir para cambiarlo. */
  file: string
  /** Nombre corto del elemento. */
  label: string
  /** Sección de la guía a la que pertenece. */
  section: string
  type: ContentType
  /** Qué tienes que escribir o aportar. */
  description: string
  /** En qué momento de la experiencia se ve. */
  where: string
  /** Formato que debe tener el valor. */
  format: string
  /** true si el regalo queda incompleto sin esto. */
  required: boolean
  /** El texto marcador que hay ahora. `null` si no lleva marcador. */
  placeholder: string | null
  /** Valor por defecto que ya funciona sin que toques nada. */
  defaultValue?: string
}


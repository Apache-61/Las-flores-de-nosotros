const idByPath = new Map<string, string>(
  contentManifest.map((item) => [item.path, item.id]),
)

/**
 * El identificador de un elemento, para marcarlo en la página con
 * `data-cid`. Devuelve `undefined` si esa ruta no está en el manifiesto,
 * así que marcar algo que no existe no rompe nada: simplemente no sale.
 */
export function cid(path: string): string | undefined {
  return idByPath.get(path)
}

